// Every database test gets its own disposable schema, never the app's tables.
func testDatabaseURL(t *testing.T) string {
	t.Helper()
	value := os.Getenv("TEST_DATABASE_URL")
	if value == "" {
		values, _ := godotenv.Read("../../../.env")
		value = values["TEST_DATABASE_URL"]
	}
	if value == "" {
		t.Skip("PostgreSQL tests need TEST_DATABASE_URL (use a separate test database or Neon branch)")
	}
	if err := validateDatabaseURL(value); err != nil {
		t.Fatal(err)
	}
	db, err := sql.Open("pgx", value)
	if err != nil {
		t.Fatal("invalid test database configuration")
	}
	schema := newID("test")
	if _, err = db.Exec("CREATE SCHEMA " + schema); err != nil {
		db.Close()
		t.Fatal("cannot create test schema; check TEST_DATABASE_URL and test database schema permissions")
	}
	config, err := pgx.ParseConfig(value)
	if err != nil {
		db.Close()
		t.Fatal("invalid test database configuration")
	}
	// Neon does not reliably apply a search_path startup parameter. Select the
	// schema after every physical connection opens, before it enters the pool.
	config.AfterConnect = func(ctx context.Context, conn *pgconn.PgConn) error {
		_, err := conn.Exec(ctx, "SET search_path TO "+pgx.Identifier{schema}.Sanitize()).ReadAll()
		return err
	}
	registered := stdlib.RegisterConnConfig(config)
	t.Cleanup(func() {
		if _, err := db.Exec("DROP SCHEMA " + schema + " CASCADE"); err != nil {
			t.Errorf("drop test schema: %v", err)
		}
		db.Close()
		stdlib.UnregisterConnConfig(registered)
	})
	return registered
}

func TestPostgresMutationsSerialize(t *testing.T) {
	store, err := OpenStore(testDatabaseURL(t))
	if err != nil {
		t.Fatal(err)
	}
	defer store.Close()
	now := time.Now().UTC()
	if err := store.Create(Experiment{ID: "concurrent", Status: "draft", CreatedAt: now, UpdatedAt: now}); err != nil {
		t.Fatal(err)
	}
	var wg sync.WaitGroup
	failures := make(chan error, 20)
	for i := 0; i < 20; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			_, err := store.Mutate("concurrent", "increment", "incremented", func(e *Experiment) error { e.Attempt++; return nil })
			if err != nil {
				failures <- err
			}
		}()
	}
	wg.Wait()
	close(failures)
	for err := range failures {
		t.Error(err)
	}
	e, err := store.Get("concurrent")
	if err != nil || e.Attempt != 20 {
		t.Fatalf("concurrent updates lost: attempt=%d, err=%v", e.Attempt, err)
	}
	events, err := store.Events(e.ID, 0, 100)
	if err != nil || len(events) != 21 {
		t.Fatalf("expected 21 committed events, got %d: %v", len(events), err)
	}
	if err = store.Delete(e.ID); err != nil {
		t.Fatal(err)
	}
	events, err = store.Events(e.ID, 0, 100)
	if err != nil || len(events) != 0 {
		t.Fatalf("event cascade failed: %v", err)
	}
}

func TestSQLiteImportPreservesRecordsAndEventSequence(t *testing.T) {
	store, err := OpenStore(testDatabaseURL(t))
	if err != nil {
		t.Fatal(err)
	}
	defer store.Close()
	source := filepath.Join(t.TempDir(), "legacy.db")
	fixture := exec.Command("python3", "-c", `
import sqlite3, sys, json
c = sqlite3.connect(sys.argv[1])
schema = sys.stdin.read().replace("BYTEA", "BLOB").replace("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY AUTOINCREMENT")
c.executescript(schema)
payloads = {
 "projects": {"id":"prj_legacy", "name":"Researcher's café"},
 "datasets": {"id":"ds_legacy", "name":"observations.csv"},
 "experiments": {"id":"exp_legacy", "title":"Legacy study", "question":"How does growth change?", "status":"planned", "plan_version":1, "created_at":"2026-01-01T00:00:00Z", "updated_at":"2026-01-01T00:00:00Z"},
 "plan_versions": {"research_question":"How does growth change?", "domain":"biology"},
 "artifacts": {"name":"attempt-001/results.json", "sha256":"abc"}
}
b = lambda table: json.dumps(payloads[table], ensure_ascii=False).encode()
c.execute("INSERT INTO projects VALUES(?,?)", ("prj_legacy", b("projects")))
c.execute("INSERT INTO datasets VALUES(?,?)", ("ds_legacy", b("datasets")))
c.execute("INSERT INTO experiments VALUES(?,?,?,?)", ("exp_legacy", "planned", "2026-01-01T00:00:00Z", b("experiments")))
c.execute("INSERT INTO plan_versions VALUES(?,?,?)", ("exp_legacy", 1, b("plan_versions")))
c.execute("INSERT INTO events VALUES(?,?,?,?,?)", (41, "exp_legacy", "created", "Researcher's café", "2026-01-01T00:00:00Z"))
c.execute("INSERT INTO artifacts VALUES(?,?,?)", ("exp_legacy", "attempt-001/results.json", b("artifacts")))
c.commit()
`, source)
	fixture.Stdin = bytes.NewBufferString(storeSchema)
	if output, err := fixture.CombinedOutput(); err != nil {
		t.Fatalf("create legacy fixture: %v %s", err, output)
	}
	export := exec.Command("python3", "../../scripts/migrate-sqlite.py", source)
	sqlBytes, err := export.Output()
	if err != nil {
		t.Fatal(err)
	}
	var schemaName string
	if err := store.db.QueryRow("SELECT current_schema()").Scan(&schemaName); err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(schemaName, "test_") {
		t.Fatal("test connection is not isolated from application tables")
	}
	if _, err = store.db.Exec(string(sqlBytes)); err != nil {
		t.Fatalf("import: %v", err)
	}
	for _, table := range []string{"projects", "datasets", "experiments", "plan_versions", "events", "artifacts"} {
		var count int
		if err = store.db.QueryRow("SELECT count(*) FROM " + table).Scan(&count); err != nil || count != 1 {
			t.Fatalf("%s count=%d err=%v", table, count, err)
		}
	}
	projects, err := store.Projects()
	if err != nil || projects[0].Name != "Researcher's café" {
		t.Fatalf("payload changed: %v", err)
	}
	if err = store.Event("exp_legacy", "reviewed", "Reviewed after import"); err != nil {
		t.Fatal(err)
	}
	events, err := store.Events("exp_legacy", 41, 10)
	if err != nil || len(events) != 1 || events[0].ID != 42 {
		t.Fatalf("identity sequence was not restored: %v %v", events, err)
	}
	// A repeat import must fail atomically, leaving all original rows intact.
	conn, err := store.db.Conn(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close()
	if _, err = conn.ExecContext(context.Background(), string(sqlBytes)); err == nil {
		t.Fatal("import into a populated database was accepted")
	}
	if _, err = conn.ExecContext(context.Background(), "ROLLBACK"); err != nil {
		t.Fatal(err)
	}
	var count int
	if err = store.db.QueryRow("SELECT count(*) FROM events").Scan(&count); err != nil || count != 2 {
		t.Fatalf("failed import changed data: count=%d err=%v", count, err)
	}
}
